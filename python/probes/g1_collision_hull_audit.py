#!/usr/bin/env python3
"""Cook and audit compound convex collision from Unitree's official G1 meshes.

The checked-in runtime data is generated by this tool from the pinned
``unitree_ros`` source revision documented in ``G1.cpp``. Deterministic
two-piece V-HACD preserves authored concavities while keeping the complete G1
below the native 64-collider topology limit. Each piece is then compacted with
aspect-ratio-normalized farthest-point sampling for inexpensive online support
mapping.

``trimesh``, ``vhacdx==0.0.10``, and ``scipy`` are cook-time-only
dependencies.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import trimesh
from scipy.spatial import ConvexHull


SOURCE_REVISION = "aa0f5c68b5aba347bad409e71b6430407da758d7"
TARGET_VOLUME_RATIO = 0.97
TARGET_VERTEX_COUNTS = (48, 64, 80, 96, 112, 128)
VHACD_VERSION = "0.0.10"
VHACD_PARAMETERS = {
    "maxConvexHulls": 2,
    "resolution": 200_000,
    "minimumVolumePercentErrorAllowed": 1.0,
    "maxRecursionDepth": 8,
    "shrinkWrap": True,
    "fillMode": "flood",
    "maxNumVerticesPerCH": 64,
    "asyncACD": False,
    "minEdgeLength": 2,
    "findBestPlane": True,
}


@dataclass(frozen=True)
class MeshSource:
    name: str
    body_index: int
    fixed_offset: tuple[float, float, float] = (0.0, 0.0, 0.0)


