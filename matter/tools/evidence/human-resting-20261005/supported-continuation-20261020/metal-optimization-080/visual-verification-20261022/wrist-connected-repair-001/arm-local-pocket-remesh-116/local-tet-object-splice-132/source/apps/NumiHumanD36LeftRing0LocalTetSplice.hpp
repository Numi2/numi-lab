struct Storage {
    std::vector<std::uint32_t> oldTetParentSurfaceFaceRows;
    std::vector<V3> oldNodeDonorLocalPoints;
    std::vector<LocalSkinFatTetNode> nodes;
    std::vector<std::uint32_t> childParentSurfaceFaceRows, childSourceFaceIdentities;
    std::vector<std::uint32_t> childDonorBodyLabels, childBasisRegionLabels;
    std::vector<std::uint32_t> noAddedContactNodes;

    [[nodiscard]] bool prepare(const numi::matter::ObjectSource& object,
            const PreparedOrganicFEM& skin, const PreparedOrganicFEM& fat,
            const RegisteredSkinFatReductionSourceLabels& labels,
            std::string& error) {
        const auto fail=[&](const char* why){ error=why; return false; };
        constexpr std::size_t N=kWholeBodySkinSourceVertexCount;
        constexpr std::size_t T=kElbowRefinementChildTetCount;
        oldTetParentSurfaceFaceRows.assign(
            kElbowRefinementChildParentSurfaceFaces.begin(),
            kElbowRefinementChildParentSurfaceFaces.end());
        if (object.representation!=numi::matter::Representation::fem ||
            object.femNodes.size()!=3u*N || object.tetrahedra.size()!=T ||
            object.femMaterialIndices.size()!=T ||
            labels.sourceNodeVertexIndices.size()!=object.femNodes.size() ||
            labels.sourceNodeLayerIndices.size()!=object.femNodes.size() ||
            labels.sourceNodeDonorBodyIndices.size()!=object.femNodes.size() ||
            labels.tetrahedronSourceDonorBodyIndices.size()!=T ||
            labels.tetrahedronBasisRegionLabels.size()!=T ||
            labels.tetrahedronSourceFaceIndices.size()!=T ||
            labels.registeredMechanicalFaceIndices.size()!=kWholeBodySkinFaceCount ||
            skin.materialIndex==fat.materialIndex || skin.materialIndex!=1u || fat.materialIndex!=2u ||
            oldTetParentSurfaceFaceRows.size()!=T) {
            return fail("D36 left ring-0 source shell, labels, or paired material reports differ from the frozen table");
        }
        for (std::size_t t=0;t<T;++t) {
            auto actual=object.tetrahedra[t].nodes;
            auto expected=kElbowRefinementChildTetrahedra[t];
            std::sort(actual.begin(),actual.end()); std::sort(expected.begin(),expected.end());
            if (actual!=expected || object.femMaterialIndices[t]!=kElbowRefinementChildMaterialCodes[t] ||
                oldTetParentSurfaceFaceRows[t]!=kElbowRefinementChildParentSurfaceFaces[t])
                return fail("D36 left ring-0 input does not match the exact frozen 28632-tet object topology");
            const auto stable=labels.tetrahedronOriginalSourceFaceIndices.empty()?
                labels.tetrahedronSourceFaceIndices[t]:labels.tetrahedronOriginalSourceFaceIndices[t];
            if (stable!=kElbowRefinementChildSourceFaceIdentities[t])
                return fail("D36 left ring-0 source stable-face identity differs from the current labels");
        }
        oldNodeDonorLocalPoints.assign(object.femNodes.size(), V3{});
        std::vector<bool> haveLocal(object.femNodes.size(),false);
        const auto first=skin.firstGlobalFEMNode;
        for (const auto& mass:skin.donorMassNodes) {
            if (mass.nodeIndex<first || mass.nodeIndex-first>=object.femNodes.size())
                return fail("D36 aggregate donor-mass node escapes the skin/fat ObjectSource");
            const auto local=static_cast<std::size_t>(mass.nodeIndex-first);
            if (haveLocal[local] || mass.donorBody!=labels.sourceNodeDonorBodyIndices[local])
                return fail("D36 aggregate donor-mass table has duplicate or mismatched node ownership");
            oldNodeDonorLocalPoints[local]=mass.localPosition; haveLocal[local]=true;
        }
        if (std::find(haveLocal.begin(),haveLocal.end(),false)!=haveLocal.end())
            return fail("D36 aggregate donor-mass table does not cover every physical object node");
        nodes.clear(); nodes.reserve(object.femNodes.size());
        const auto& refs=object.femReferenceNodes.empty()?object.femNodes:object.femReferenceNodes;
        for (std::uint32_t g=0;g<object.femNodes.size();++g) {
            LocalSkinFatTetNode n; n.existingObjectNode=g; n.world=object.femNodes[g]; n.referenceWorld=refs[g];
            n.donorLocal=oldNodeDonorLocalPoints[g]; n.donorBody=labels.sourceNodeDonorBodyIndices[g];
            n.sourceVertex=labels.sourceNodeVertexIndices[g]; n.layerOrInterior=labels.sourceNodeLayerIndices[g];
            nodes.push_back(n);
        }
        childParentSurfaceFaceRows.resize(kChildTetrahedra.size());
        childSourceFaceIdentities.resize(kChildTetrahedra.size());
        childDonorBodyLabels.resize(kChildTetrahedra.size());
        childBasisRegionLabels.resize(kChildTetrahedra.size());
        for (std::size_t c=0;c<kChildTetrahedra.size();++c) {
            const auto p=kChildRepresentativeParentTetRows[c];
            if (p>=T || object.femMaterialIndices[p]!=kChildMaterials[c])
                return fail("D36 ring-0 child representative parent is outside or has a different material");
            childParentSurfaceFaceRows[c]=kElbowRefinementChildParentSurfaceFaces[p];
            childSourceFaceIdentities[c]=kElbowRefinementChildSourceFaceIdentities[p];
            childDonorBodyLabels[c]=labels.tetrahedronSourceDonorBodyIndices[p];
            childBasisRegionLabels[c]=labels.tetrahedronBasisRegionLabels[p];
        }
        error.clear(); return true;
    }

    [[nodiscard]] LocalSkinFatTetSpliceInput input(const numi::matter::ObjectSource& object,
            const PreparedOrganicFEM& skin, const PreparedOrganicFEM& fat) const {
        LocalSkinFatTetSpliceInput in;
        in.replacedTetRows=kReplacedTetRows;
        in.oldTetParentSurfaceFaceRows=oldTetParentSurfaceFaceRows;
        in.oldNodeDonorLocalPoints=oldNodeDonorLocalPoints;
        in.nodes=nodes;
        in.childTetrahedra=kChildTetrahedra;
        in.childMaterialIndices=kChildMaterials;
        in.childParentTetRows=kChildRepresentativeParentTetRows;
        in.childParentSurfaceFaceRows=childParentSurfaceFaceRows;
        in.childSourceFaceIdentities=childSourceFaceIdentities;
        in.childDonorBodyLabels=childDonorBodyLabels;
        in.childBasisRegionLabels=childBasisRegionLabels;
        in.addedContactLocalNodeIndices=noAddedContactNodes;
        in.materialSourceIdentity=object.femMaterialSourceIdentity;
        in.materialFrameSourceIdentity=object.femMaterialFrameSourceIdentity;
        in.referenceSourceIdentity=object.femReferenceSourceIdentity;
        (void)skin; (void)fat;
        return in;
    }
};
