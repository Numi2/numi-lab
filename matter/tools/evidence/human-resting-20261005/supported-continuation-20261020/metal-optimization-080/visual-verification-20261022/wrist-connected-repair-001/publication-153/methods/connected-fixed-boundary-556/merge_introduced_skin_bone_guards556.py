def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def array_sha(array):
    return hashlib.sha256(np.ascontiguousarray(array).view(np.uint8)).hexdigest()


def same(a, b):
    return a.dtype == b.dtype and a.shape == b.shape and a.tobytes(order="C") == b.tobytes(order="C")


def load_npz(path):
    with np.load(path, allow_pickle=False) as z:
        return {k: np.array(z[k], copy=True) for k in z.files}


def load_json(path):
    obj = json.loads(Path(path).read_text())
    if not isinstance(obj, dict):
        raise ValueError("JSON object expected: " + str(path))
    return obj


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot import owner: " + str(path))
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def pair_map(arrays, face_count):
    missing = [k for k in (*ID_ARRAYS, TRI_ARRAY) if k not in arrays]
    if missing:
        raise ValueError(f"guard NPZ missing arrays: {missing}")
    ids = {}
    count = None
    for key in ID_ARRAYS:
        raw = np.asarray(arrays[key])
        if raw.ndim != 1 or raw.dtype.kind not in "iu":
            raise ValueError(f"{key} must be a one-dimensional integer array")
        if count is None:
            count = len(raw)
        elif len(raw) != count:
            raise ValueError("typed identity arrays have different lengths")
        vals = raw.astype(np.int64, copy=False)
        if np.any(vals < 0):
            raise ValueError(f"{key} contains negative IDs")
        ids[key] = vals
    n = int(count or 0)
    triangles = np.asarray(arrays[TRI_ARRAY])
    if triangles.dtype != np.dtype(np.float64) or triangles.shape != (n, 3, 3) or not np.isfinite(triangles).all():
        raise ValueError("fixed triangles must be finite Float64 world-mm (K,3,3)")
    if np.any(ids["skin_face_rows"] >= face_count):
        raise ValueError("skin face row is outside bound base topology")
    result = {}
    for i in range(n):
        key = (int(ids["skin_face_rows"][i]), int(ids["bank_body"][i]),
               int(ids["stable_bone_id"][i]), int(ids["bank_triangle_stable_id"][i]))
        if key in result:
            raise ValueError(f"duplicate typed pair identity in payload: {key}")
        result[key] = triangles[i].copy()
    return result


def merge_pair_arrays(existing, introduced, face_count, canonical_emit):
    """Union typed identities and require bitwise-equal bank geometry on overlap."""
    old = pair_map(existing, face_count)
    new = pair_map(introduced, face_count)
    overlap = set(old) & set(new)
    for key in sorted(overlap):
        if not same(old[key], new[key]):
            raise ValueError(f"bank geometry differs for duplicate typed pair {key}")
    union = set(old) | set(new)
    # The 314 emitter accepts (body,bone,face,triangle) and canonicalizes order.
    emit_pairs = [(body, bone, face, tri) for face, body, bone, tri in sorted(union)]
    merged = canonical_emit(emit_pairs)
    canonical = pair_map(merged, face_count)
    if set(canonical) != union:
        raise AssertionError("314 canonical emitter changed typed identities")
    for key, tri in {**old, **new}.items():
        if not same(canonical[key], tri):
            raise ValueError(f"canonical pinned bank geometry differs for typed pair {key}")
    return merged, {
        "existing_pair_count": len(old),
        "introduced_pair_count": len(new),
        "overlap_pair_count_deduplicated": len(overlap),
        "merged_pair_count": len(union),
        "identity_contract": "(skin_face_row, bank_body, stable_bone_id, bank_triangle_stable_id)",
        "fixed_geometry_rebuilt_by_pinned_314": True,
        "duplicate_geometry_must_match_bitwise": True,
    }


def make_report_pairs(keys):
    return [
        {"skin_face_row": int(face), "bank_body": int(body),
         "stable_bone_id": int(bone), "bank_triangle_stable_id": int(tri)}
        for body, bone, face, tri in sorted(keys)
    ]


def verify_bank_pins(report, emitter, bank_pins):
    if report.get("bank_reader_path") != emitter.BANK_HELPER.as_posix():
        raise ValueError("bank reader path differs from pinned 314 owner")
    if report.get("bank_reader_sha256") != sha(emitter.BANK_HELPER):
        raise ValueError("bank reader hash differs from pinned 314 owner")
    if report.get("bank_source_pins") != bank_pins:
        raise ValueError("bank source inventory differs from pinned 039 bank files")
    paths = report.get("bank_source_paths")
    if paths is not None:
        expected = {name: (emitter.BANK_DIR / name).as_posix() for name in bank_pins}
        if paths != expected:
            raise ValueError("bank source path map differs from pinned 039 directory")
    for name, digest in bank_pins.items():
        path = emitter.BANK_DIR / name
        if not path.is_file() or sha(path) != digest:
            raise ValueError(f"039 source bank pin mismatch: {path}")


def validate_314_inputs(report, base_candidate, base_sha, base_points, base_faces, emitter, bank_keys):
    inputs = report.get("inputs")
    if not isinstance(inputs, list):
        raise ValueError("314 export lacks audit input provenance")
    base_rows = [r for r in inputs if isinstance(r, dict) and r.get("role") == "base"]
    trial_rows = [r for r in inputs if isinstance(r, dict) and r.get("role") == "trial"]
    if len(base_rows) != 1 or not trial_rows:
        raise ValueError("314 export requires one base audit and at least one trial")
    sets, receipts = [], []
    for i, row in enumerate(inputs):
        if not isinstance(row, dict):
            raise ValueError("malformed 314 audit input row")
        report_path, candidate_path = Path(row["report_path"]), Path(row["candidate_path"])
        if not report_path.is_file() or sha(report_path) != row.get("report_sha256"):
            raise ValueError(f"159 report provenance mismatch: {report_path}")
        if not candidate_path.is_file() or sha(candidate_path) != row.get("candidate_sha256"):
            raise ValueError(f"audit candidate provenance mismatch: {candidate_path}")
        audit = load_json(report_path)
        if audit.get("candidate_sha256") != row["candidate_sha256"]:
            raise ValueError("159 report and candidate identity disagree")
        with np.load(candidate_path, allow_pickle=False) as z:
            pts, faces = np.asarray(z["points_world_m"]), np.asarray(z["source_O_faces"])
        if pts.dtype != np.float32 or pts.shape != base_points.shape or faces.dtype != base_faces.dtype or not same(faces, base_faces):
            raise ValueError("trial candidate changes point domain or face topology")
        pairset = emitter.validate_audit_report(
            audit, candidate_sha256=row["candidate_sha256"],
            point_count=len(base_points), face_count=len(base_faces),
            expected_bank_keys=bank_keys,
            expected_script_sha256=sha(emitter.AUDIT_159),
            expected_predicate_sha256=sha(emitter.EXACT_159),
        )
        sets.append(pairset)
        receipts.append({
            "role": row.get("role"), "candidate_path": str(candidate_path),
            "candidate_sha256": row["candidate_sha256"],
            "report_path": str(report_path), "report_sha256": row["report_sha256"],
            "typed_pair_count": len(pairset),
        })
        if i == 0 and row.get("role") != "base":
            raise ValueError("314 base audit must be first")
    first = base_rows[0]
    if Path(first["candidate_path"]) != base_candidate or first["candidate_sha256"] != base_sha:
        raise ValueError("314 base audit does not match merged base candidate")
    base_pairs = sets[0]
    trial_union = set().union(*sets[1:])
    introduced = set(emitter.introduced_pairs(base_pairs, sets[1:]))
    if report.get("base_pair_count") != len(base_pairs):
        raise ValueError("314 base pair count differs from revalidated audit")
    if report.get("trial_union_pair_count") != len(trial_union):
        raise ValueError("314 trial union count differs from revalidated audits")
    if report.get("introduced_pair_count") != len(introduced):
        raise ValueError("314 introduced count differs from revalidated audits")
    return introduced, receipts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-candidate", type=Path, required=True)
    parser.add_argument("--expected-base-sha256", required=True)
    parser.add_argument("--context", type=Path, required=True)
    parser.add_argument("--introduced-report", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    if args.output_dir.exists():
        raise FileExistsError(args.output_dir)
    for path, expected in PINS.items():
        if not path.is_file() or sha(path) != expected:
            raise ValueError(f"source owner pin mismatch: {path}")

    ctx = load_json(args.context)
    base_sha = sha(args.base_candidate)
    if base_sha != args.expected_base_sha256 or ctx.get("candidate_sha256") != base_sha:
        raise ValueError("base candidate, expected hash, and context candidate differ")
    if Path(ctx.get("candidate", "")) != args.base_candidate:
        raise ValueError("context base candidate path differs from CLI")
    old_npz_path, old_report_path = Path(ctx["guard_npz"]), Path(ctx["guard_report"])
    old_npz, old_report = load_npz(old_npz_path), load_json(old_report_path)
    new_report = load_json(args.introduced_report)
    new_npz_path = args.introduced_report.parent / str(new_report.get("output_npz", ""))
    if not new_npz_path.is_file() or new_npz_path.name != new_report.get("output_npz"):
        raise ValueError("introduced 314 NPZ is missing or report output is not a sibling")
    new_npz = load_npz(new_npz_path)
    base_payload = load_npz(args.base_candidate)
    points, faces = base_payload.get("points_world_m"), base_payload.get("source_O_faces")
    if points is None or faces is None or points.dtype != np.float32 or faces.ndim != 2 or faces.shape[1] != 3:
        raise ValueError("base point/face arrays malformed")

    emitter = load_module(EMITTER314, "emitter314_merge556")
    phase = load_module(OWNER401, "validator401_merge556")
    fixed_owner = load_module(OWNER313, "fixed313_merge556")
    pair_owner = load_module(OWNER026, "pairs026_merge556")
    bank = emitter._module("bankreader314_merge556", emitter.BANK_HELPER)
    triangles, ids, _gids, _bodies, matrices, offsets, positions, bankkeys, bank_pins, _unused = bank.read_bank_inputs(emitter.BANK_DIR, emitter.BANK_EVIDENCE)
    expected_keys = tuple((int(row[0]), int(row[1])) for row in np.asarray(bankkeys))
    if len(expected_keys) != 185 or len(set(expected_keys)) != 185:
        raise ValueError("pinned source inventory is not 185 unique typed banks")
    bank_key_set = set(expected_keys)
    triangle_lookup = emitter.typed_triangle_lookup(triangles, ids)
    transforms = {int(b):(matrices[int(b)], offsets[int(b)], positions[int(b)]) for b in matrices}

    for report, label in ((old_report, "existing guard"), (new_report, "introduced export")):
        if report.get("status") != "COMPLETE_TYPED_INTRODUCED_SKIN_BONE_BARRIER_EXPORT" or report.get("schema") != SCHEMA:
            raise ValueError(f"{label} report is not a complete 314-schema payload")
        if report.get("base_candidate_sha256") != base_sha or report.get("bank_count") != 185 or report.get("expected_bank_count") != 185:
            raise ValueError(f"{label} report base/bank domain mismatch")
        if report.get("bank_reader_path") != emitter.BANK_HELPER.as_posix() or report.get("bank_reader_sha256") != sha(emitter.BANK_HELPER):
            raise ValueError(f"{label} bank-reader provenance mismatch")
        verify_bank_pins(report, emitter, bank_pins)
        if report.get("geometry_or_native_admission") is not False:
            raise ValueError(f"{label} must remain construction-only")

    # Validate each input payload independently against the existing 401 schema.
    old_records, old_receipt = phase.validate_fixed_boundary_payload(
        old_npz, old_report, candidate_sha256=base_sha,
        candidate_points=points, candidate_faces=faces, npz_path=old_npz_path)
    new_records, new_receipt = phase.validate_fixed_boundary_payload(
        new_npz, new_report, candidate_sha256=base_sha,
        candidate_points=points, candidate_faces=faces, npz_path=new_npz_path)
    old_map = pair_map(old_npz, len(faces))
    new_map = pair_map(new_npz, len(faces))
    for identity_map, label in ((old_map, "existing guard"), (new_map, "introduced export")):
        for face, body, bone, tri in identity_map:
            if (body, bone) not in bank_key_set or (body, bone, tri) not in triangle_lookup:
                raise ValueError(f"{label} has unknown typed bank triangle {(body,bone,tri)}")
    introduced_keys, audit_receipts = validate_314_inputs(
        new_report, args.base_candidate, base_sha, points, faces, emitter, expected_keys)
    npz_introduced_keys = {(body, bone, face, tri) for face,body,bone,tri in new_map}
    if npz_introduced_keys != introduced_keys:
        raise ValueError("314 NPZ identities differ from revalidated trial-union minus base audits")

    merged, stats = merge_pair_arrays(
        old_npz, new_npz, len(faces),
        lambda pairs: emitter.make_barrier_arrays(pairs, triangle_lookup, transforms))
    merged_map = pair_map(merged, len(faces))
    merged_keys = {(body,bone,face,tri) for face,body,bone,tri in merged_map}

    # Run the existing 313 owner over the whole union at the pinned base.
    merged_records = [
        {"skin_face_row": face, "bank_body": body, "stable_bone_id": bone,
         "bank_triangle_stable_id": tri, "fixed_triangle_world_mm": tri_xyz}
        for (face,body,bone,tri),tri_xyz in sorted(merged_map.items())
    ]
    rows, typed_rows = phase.build_fixed_boundary_barriers(
        points.astype(np.float64)*1000.0, faces, merged_records,
        pair_owner, fixed_owner, margin_fraction=0.25)
    if len(rows) != 6*len(merged_records) or len(typed_rows) != len(merged_records):
        raise ValueError("original 313 row count or typed range validation failed")
    if any(float(row["lower"]) > 2e-8 for row in rows):
        raise ValueError("merged 313 rows are not zero-step feasible on pinned base")

    args.output_dir.mkdir(parents=True, exist_ok=False)
    out_npz = args.output_dir / "introduced-skin-bone-barriers.npz"
    np.savez_compressed(out_npz, **merged)
    report = dict(new_report)
    report.update({
        "base_candidate_path": str(args.base_candidate),
        "base_candidate_sha256": base_sha,
        "candidate_points_world_m_array_sha256": array_sha(points),
        "skin_faces_array_sha256": array_sha(faces),
        "point_count": len(points), "face_count": len(faces),
        "candidate_points_world_m_shape": list(points.shape),
        "skin_faces_shape": list(faces.shape),
        "bank_count": 185, "expected_bank_count": 185,
        "fixed_triangles_units": "mm", "fixed_triangles_frame": "world",
        "introduced_pair_count": len(merged_records),
        "typed_pairs": make_report_pairs(merged_keys),
        "output_npz": out_npz.name, "output_npz_sha256": sha(out_npz),
        "geometry_or_native_admission": False,
        "inputs": [
            *new_report["inputs"],
            {"role":"existing_current_guard_payload",
             "candidate_path":old_report.get("base_candidate_path"),
             "candidate_sha256":base_sha,"report_path":str(old_report_path),
             "report_sha256":sha(old_report_path),"npz_path":str(old_npz_path),
             "npz_sha256":sha(old_npz_path),"typed_pair_count":len(old_records)},
            {"role":"introduced_314_export","report_path":str(args.introduced_report),
             "report_sha256":sha(args.introduced_report),"npz_path":str(new_npz_path),
             "npz_sha256":sha(new_npz_path),"typed_pair_count":len(new_records)},
        ],
        "merge_provenance": {
            "existing_context_path":str(args.context),"existing_context_sha256":sha(args.context),
            "existing_guard_report_path":str(old_report_path),"existing_guard_report_sha256":sha(old_report_path),
            "existing_guard_npz_path":str(old_npz_path),"existing_guard_npz_sha256":sha(old_npz_path),
            "introduced_314_report_path":str(args.introduced_report),"introduced_314_report_sha256":sha(args.introduced_report),
            "introduced_314_npz_path":str(new_npz_path),"introduced_314_npz_sha256":sha(new_npz_path),
            "revalidated_314_audit_inputs":audit_receipts,
            "old_payload_401_receipt":old_receipt,"introduced_payload_401_receipt":new_receipt,
            "merged_pair_union":stats,
            "original_313_zero_step_validation":{"status":"PASS","row_count":len(rows),
                "typed_pair_count":len(typed_rows),"all_lower_bounds_zero_feasible":True,
                "margin_fraction":0.25},
        },
        "source_pins": {
            str(Path(__file__).resolve()):sha(Path(__file__)),
            str(EMITTER314):sha(EMITTER314),str(OWNER313):sha(OWNER313),
            str(OWNER401):sha(OWNER401),str(OWNER026):sha(OWNER026),
            str(emitter.BANK_HELPER):sha(emitter.BANK_HELPER),
            str(emitter.AUDIT_159):sha(emitter.AUDIT_159),
            str(emitter.EXACT_159):sha(emitter.EXACT_159),
            str(args.base_candidate):base_sha,str(args.context):sha(args.context),
            str(old_report_path):sha(old_report_path),str(old_npz_path):sha(old_npz_path),
            str(args.introduced_report):sha(args.introduced_report),str(new_npz_path):sha(new_npz_path),
            **{str(emitter.BANK_DIR/name):digest for name,digest in bank_pins.items()},
            **{r["report_path"]:r["report_sha256"] for r in audit_receipts},
            **{r["candidate_path"]:r["candidate_sha256"] for r in audit_receipts},
        },
        "construction_scope": {
            **new_report.get("construction_scope", {}),
            "selection_scope":"EXISTING_CURRENT_541_GUARDS_UNION_REVALIDATED_314_INTRODUCED_PAIRS",
            "existing_guard_pair_count":stats["existing_pair_count"],
            "introduced_pair_count_before_deduplication":stats["introduced_pair_count"],
            "duplicate_pairs_deduplicated":stats["overlap_pair_count_deduplicated"],
            "merged_guard_pair_count":stats["merged_pair_count"],
            "new_constraints_zero_step_feasible_on_base":True,
            "absence_from_guard_subset_does_not_establish_clearance":True,
        },
        "limitations":list(new_report.get("limitations",[]))+[
            "Merged payload is an incremental construction guard subset, not a complete current surface audit.",
            "All old and introduced typed pairs passed original 313 row construction at the zero-displacement base.",
            "No fit, geometry audit, physical admission, or native qualification was performed by this merger.",
        ],
    })
    phase.validate_fixed_boundary_payload(
        load_npz(out_npz), report, candidate_sha256=base_sha,
        candidate_points=points,candidate_faces=faces,npz_path=out_npz)
    report_path=args.output_dir/"report.json"
    report_path.write_text(json.dumps(report,indent=2,sort_keys=True,allow_nan=False)+"\n")
    print(json.dumps({
        "status":report["status"],"base_candidate_sha256":base_sha,
        "existing_guard_pairs":stats["existing_pair_count"],
        "introduced_pairs":stats["introduced_pair_count"],
        "deduplicated_overlap":stats["overlap_pair_count_deduplicated"],
        "merged_pair_count":stats["merged_pair_count"],
        "validated_313_rows":len(rows),"npz":str(out_npz),
        "npz_sha256":sha(out_npz),"report":str(report_path),
    }),flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

